"""Generates the pixel-art launcher icon and Play Store graphics from one grid.

    uv run --with pillow tools/icon.py

Writes the adaptive icon vectors into app/src/main/res/drawable and the
store graphics into fastlane/metadata/android/en-US/images.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent

# A stack of cargo crates on a pallet, after the crates.io logo.
ART = """
.....KKKKKKKKKK.....
.....KHHHHHHHHK.....
.....KHHHHHHHHK.....
.....KYYYTTYYSK.....
.....KYYYTTYYSK.....
.....KYYYTTYYSK.....
.....KSSSSSSSSK.....
KKKKKKKKKKKKKKKKKKKK
KHHHHHHHHKKHHHHHHHHK
KHHHHHHHHKKHHHHHHHHK
KYYYTTYYSKKYYYTTYYSK
KYYYTTYYSKKYYYTTYYSK
KYYYTTYYSKKYYYTTYYSK
KYYYTTYYSKKYYYTTYYSK
KSSSSSSSSKKSSSSSSSSK
KKKKKKKKKKKKKKKKKKKK
PPPPPPPPPPPPPPPPPPPP
pppppppppppppppppppp
.ppp.....pp.....ppp.
.ppp.....pp.....ppp.
""".strip().splitlines()

COLORS = {
    "K": "#3D2208",  # outline
    "H": "#FFE08A",  # lid, catching the light
    "Y": "#FFC933",  # crates.io yellow
    "T": "#E8A92A",  # packing tape
    "S": "#D99A1E",  # shade
    "P": "#9A6430",  # pallet
    "p": "#6B4220",  # pallet shade
}
GREEN = "#3B6837"  # crates.io green
# Themed (monochrome) icons only keep the alpha shape, so draw the line work.
MONO = {"K", "T", "P", "p"}

SIZE = len(ART)
assert all(len(row) == SIZE for row in ART)


def runs(keep):
    """(x, y, width) for each horizontal run of pixels whose colour passes keep."""
    for y, row in enumerate(ART):
        x = 0
        while x < SIZE:
            if keep(row[x]):
                start = x
                while x < SIZE and row[x] == row[start] and keep(row[x]):
                    x += 1
                yield start, y, x - start, row[start]
            else:
                x += 1


def vector(paths):
    body = "\n".join(
        f'    <path android:fillColor="{color}" android:pathData="{data}" />' for color, data in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
"""


def art_paths(keep, color_of):
    # 20 px * 2 = 40 units, so even the corners stay inside the 66 unit safe-zone
    # circle of the 108 canvas; 2 also lands on whole device pixels at most densities.
    px, offset = 2, 34
    by_color = {}
    for x, y, w, c in runs(keep):
        d = f"M{offset + x * px},{offset + y * px}h{w * px}v{px}h{-w * px}z"
        by_color.setdefault(color_of(c), []).append(d)
    return [(color, "".join(ds)) for color, ds in by_color.items()]


def write_vectors():
    res = ROOT / "app/src/main/res/drawable"
    (res / "ic_launcher_foreground.xml").write_text(
        vector(art_paths(lambda c: c in COLORS, COLORS.get))
    )
    (res / "ic_launcher_monochrome.xml").write_text(
        vector(art_paths(lambda c: c in MONO, lambda c: "#FFFFFFFF"))
    )
    (res / "ic_launcher_background.xml").write_text(vector([(GREEN, "M0,0h108v108h-108z")]))


def draw_art(img, left, top, px):
    d = ImageDraw.Draw(img)
    for y, row in enumerate(ART):
        for x, c in enumerate(row):
            if c in COLORS:
                d.rectangle(
                    [left + x * px, top + y * px, left + (x + 1) * px - 1, top + (y + 1) * px - 1],
                    fill=COLORS[c],
                )


def write_store_images():
    out = ROOT / "fastlane/metadata/android/en-US/images"
    out.mkdir(parents=True, exist_ok=True)

    # Play icon: 512x512, full bleed; Play applies its own mask.
    icon = Image.new("RGB", (512, 512), GREEN)
    draw_art(icon, (512 - SIZE * 16) // 2, (512 - SIZE * 16) // 2, 16)
    icon.save(out / "icon.png")

    # Feature graphic: 1024x500, no transparency.
    fonts = Path("/usr/share/fonts/opentype/fira")
    title = ImageFont.truetype(str(fonts / "FiraSans-Bold.otf"), 116)
    tagline = ImageFont.truetype(str(fonts / "FiraSans-Regular.otf"), 40)
    banner = Image.new("RGB", (1024, 500), GREEN)
    d = ImageDraw.Draw(banner)
    # Pixel floor under the crates.
    d.rectangle([0, 410, 1024, 500], fill="#2F5A2C")
    for x in range(0, 1024, 32):
        d.rectangle([x, 410, x + 15, 425], fill="#356331")
    draw_art(banner, 96, 410 - SIZE * 16 + 16 * 2, 16)  # pallet legs stand on the floor
    d.text((500, 150), "Crates", font=title, fill="#FFFFFF")
    d.rectangle([506, 290, 506 + 12 * 16, 290 + 11], fill=COLORS["Y"])
    d.text((502, 318), "crates.io in your pocket", font=tagline, fill="#DCEBD7")
    banner.save(out / "featureGraphic.png")


if __name__ == "__main__":
    write_vectors()
    write_store_images()
